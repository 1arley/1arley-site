#!/usr/bin/env node
/**
 * generate-preloader-paths.mjs
 *
 * Extracts per-letter SVG outlines for the "ARTHUR IARLEY" wordmark from
 * Anton-Regular.ttf (opentype.js) and emits them as a typed TS module used by
 * the Preloader stroke-draw animation.
 *
 *   node scripts/generate-preloader-paths.mjs
 *
 * Each glyph becomes its own <path> with ABSOLUTE coordinates (no translate
 * trickery) so stroke-draw via `pathLength={1}` + `strokeDashoffset` works
 * per-letter. The emitted PRELOADER_VIEWBOX is computed from the union of all
 * glyph bounds plus a margin.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FONT_PATH = path.join(ROOT, "scripts/assets/Anton-Regular.ttf");
const OUT_PATH = path.join(ROOT, "src/data/preloader-paths.ts");

const WORD = "ARTHUR IARLEY";
const FONT_SIZE = 250; // em square used to rasterize outlines
const LETTER_GAP = 8; // horizontal padding between letters (output units)
const SPACE_WIDTH = 100; // width reserved for the space between ARTHUR and IARLEY
const MARGIN = 40; // breathing room around the wordmark in the viewBox

const round = (n, d = 1) => {
  const f = 10 ** d;
  return Math.round(n * f) / f;
};

if (!fs.existsSync(FONT_PATH)) {
  console.error(`[generate-preloader-paths] font not found: ${FONT_PATH}`);
  console.error("Download it first:");
  console.error("  mkdir -p scripts/assets && curl -L https://github.com/google/fonts/raw/main/ofl/anton/Anton-Regular.ttf -o scripts/assets/Anton-Regular.ttf");
  process.exit(1);
}

// v2 API: opentype.parse(ArrayBuffer) replaces the deprecated loadSync().
const font = opentype.parse(fs.readFileSync(FONT_PATH).buffer);
const scale = FONT_SIZE / font.unitsPerEm;

let cursorX = 0;
const paths = [];
let minX = Infinity;
let maxX = -Infinity;
let minY = Infinity;
let maxY = -Infinity;

for (const char of WORD) {
  if (char === " ") {
    // Space: no outline, just advance the pen.
    cursorX += SPACE_WIDTH;
    continue;
  }
  const glyph = font.charToGlyph(char);
  const glyphPath = glyph.getPath(cursorX, 0, FONT_SIZE);
  const bbox = glyphPath.getBoundingBox();
  const d = glyphPath.toPathData(2); // absolute-coordinate SVG path data
  const advance = glyph.advanceWidth * scale;

  paths.push({
    id: paths.length,
    char,
    d,
    x: round(cursorX),
    y: 0,
    width: round(advance),
  });

  minX = Math.min(minX, bbox.x1);
  maxX = Math.max(maxX, bbox.x2);
  minY = Math.min(minY, bbox.y1);
  maxY = Math.max(maxY, bbox.y2);

  cursorX += advance + LETTER_GAP;
}

const viewBox = `${round(minX - MARGIN)} ${round(minY - MARGIN)} ${Math.ceil(maxX - minX + MARGIN * 2)} ${Math.ceil(maxY - minY + MARGIN * 2)}`;

const lines = [];
lines.push(`// AUTO-GENERATED by scripts/generate-preloader-paths.mjs — do not edit.`);
lines.push(`// Outlines extracted from public/fonts/Anton-Regular.ttf ("${WORD}", ${FONT_SIZE}px em).`);
lines.push(``);
lines.push(`export interface GlyphPath {`);
lines.push(`  id: number;`);
lines.push(`  char: string;`);
lines.push(`  d: string;`);
lines.push(`  x: number;`);
lines.push(`  y: number;`);
lines.push(`  width: number;`);
lines.push(`}`);
lines.push(``);
lines.push(`/** ViewBox that exactly fits all glyphs (glyph bounds + ${MARGIN}px margin). */`);
lines.push(`export const PRELOADER_VIEWBOX = ${JSON.stringify(viewBox)};`);
lines.push(``);
lines.push(`export const preloaderPaths: GlyphPath[] = [`);
for (const p of paths) {
  lines.push(
    `  { id: ${p.id}, char: ${JSON.stringify(p.char)}, d: ${JSON.stringify(p.d)}, x: ${p.x}, y: ${p.y}, width: ${p.width} },`,
  );
}
lines.push(`];`);
lines.push(``);

fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, lines.join("\n"));
console.log(
  `[generate-preloader-paths] wrote ${path.relative(ROOT, OUT_PATH)} (${paths.length} glyphs, viewBox ${viewBox})`,
);
